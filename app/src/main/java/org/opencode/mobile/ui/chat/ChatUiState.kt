package org.opencode.mobile.ui.chat

import androidx.compose.runtime.getValue
import androidx.compose.runtime.mutableStateOf
import androidx.compose.runtime.saveable.Saver
import androidx.compose.runtime.setValue
import org.opencode.mobile.ui.ChatNotice
import org.opencode.mobile.ui.ChatSnapshot

/**
 * Состояние экрана чата, которое меняется от действий пользователя или от сети.
 *
 * Зачем отдельный объект: в `ChatOverlay` эти пять значений были разбросаны по
 * десятку строк `remember` вперемешку с локальными переменными отрисовки, и вопрос
 * «кто это пишет и когда сбрасывает» приходилось выяснять по всему файлу на 2000
 * строк. Теперь правила записи лежат рядом с полями, а экран только читает их.
 *
 * Живёт в `rememberSaveable` (см. [saver]): переживает пересоздание Activity и смерть
 * процесса — но только черновиком.
 */
internal class ChatUiState(
    initialDraft: String = "",
) {
    /**
     * Последний снимок сессии с сервера. `null` — успешных опросов ещё не было.
     *
     * Единственный источник ленты: пишется только из опроса и из оптимистичной
     * вставки своего сообщения, поэтому лента не «дорисовывается» в обход сервера.
     * Не сохраняется: восстановить его нечем, актуальный придёт первым же опросом.
     */
    var snapshot: ChatSnapshot? by mutableStateOf(null)

    /**
     * Текст в поле ввода. Единственное значение, которое переживает смерть процесса:
     * потеря набранного из-за смены размера шрифта или возврата из другого приложения
     * — реальный ущерб, а взять его больше неоткуда.
     */
    var draft: String by mutableStateOf(initialDraft)

    /**
     * Промпт отправлен, ответа ещё нет. Держит кнопку отправки занятой, чтобы второй
     * промпт не лёг поверх незавершённого хода.
     *
     * Не сохраняется намеренно: после смерти процесса корутины отправки уже нет, и
     * восстановленный `true` оставил бы кнопку вечно занятой.
     */
    var sending: Boolean by mutableStateOf(false)

    /**
     * Остановка запрошена, сервер ещё не подтвердил. С [sending] по смыслу
     * взаимоисключающе, но не по коду: обе кнопки гасятся отдельно, потому что
     * подтверждение остановки приходит своим путём. Не сохраняется по той же
     * причине, что и [sending].
     */
    var stopping: Boolean by mutableStateOf(false)

    /**
     * Защёлка на плашку причины. Retry/ошибка провайдера — УСТОЙЧИВОЕ состояние, а не
     * событие: сервер будет отдавать free_tier_limit и после любого TTL, пока квота не
     * восстановится. Поэтому плашка держится, пока идёт ход, и гаснет только когда
     * opencode дошёл до успешного assistant-шага (thinking снят).
     *
     * Не сохраняется: без контекста хода плашка повисла бы над мёртвой сессией.
     */
    var noticeLatch: ChatNotice? by mutableStateOf(null)

    companion object {
        /**
         * Сохраняет только черновик — почему именно его, расписано в [draft],
         * [sending] и [noticeLatch].
         *
         * Ключ `String`, а не список полей: лишнее поле в Bundle переживает смерть
         * процесса и притворяется живым состоянием, которого уже нет.
         */
        val saver: Saver<ChatUiState, String> = Saver(
            save = { it.draft },
            restore = { ChatUiState(initialDraft = it) },
        )
    }
}
