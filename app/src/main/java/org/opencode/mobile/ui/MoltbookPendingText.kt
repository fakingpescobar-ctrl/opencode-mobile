package org.opencode.mobile.ui

/**
 * Показывать ли оригинал текста вопроса.
 *
 * Макс сформулировал прямо: «сообщения что вылазит с переводом под ними текст
 * на английском или других языках они не нужны только русский язык». Значит,
 * при наличии перевода оригинал не показывается никогда; без перевода —
 * показывается, иначе вопрос выглядел бы пустым.
 *
 * Отдельный файл, а не строка в MoltbookPanel.kt: там уже десять функций, и
 * detekt-лимит файла — одиннадцать. Функция, добавленная ради теста, не имеет
 * права двигать чужой файл через порог; заодно правило «есть перевод → оригинал
 * не нужен» теперь лежит рядом с собственным тестом, а не среди вёрстки.
 */
internal fun showOriginal(
    bodyRu: String,
    body: String,
): Boolean = bodyRu.isBlank() && body.isNotBlank()
