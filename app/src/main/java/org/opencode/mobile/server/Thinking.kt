package org.opencode.mobile.server

import org.json.JSONArray
import org.json.JSONObject

/**
 * Размышление модели, которое она не отдала в канале reasoning, приходит в
 * обычный текст ответа. Наблюдалось на `opencode/big-pickle` (14.10.2026):
 * сервер вернул `tokens.reasoning = 0` и один `content` типа `text`, в котором
 * шёл английский монолог, закрытый тегом `</think>`, а уже после него — сам
 * ответ на русском. В ленте это читалось как «модель что-то думает вслух».
 *
 * Тег закрывающий, открывающего в тексте нет: модель пишет `<think>` в
 * скрытом префиксе запроса, а в видимой части остаётся только хвост размышления
 * вместе с закрывающим тегом. Поэтому режем по `</think>`, а не по паре тегов.
 */
internal const val THINK_CLOSE = "</think>"

/** Тип сообщения, текст которого может оказаться размышлением. */
internal const val THINKING_TYPE = "assistant"

/**
 * Сколько ждать, прежде чем показать текст незавершённого потока как есть.
 *
 * Страховка от «вечной тишины»: если сервер не пришлёт ни `finish`, ни
 * `time.completed` (обрыв потока, падение провайдера, потеря события), ответ
 * без тега `</think>` не показался бы никогда. Спустя это время мы уже не
 * различаем мысль и ответ — показываем, что есть, потому что молчащий чат
 * хуже видимого монолога.
 *
 * Отсчёт ведётся от `time.streamed` — времени последнего обновления потока, а
 * не от `time.created`. Это принципиально: у агента с вызовами инструментов
 * живой поток идёт минутами, и порог по `created` начал бы показывать мысль
 * через 15 секунд такого потока, то есть ровно то, ради чего всё затевалось.
 * Если сервер `streamed` не отдаёт, порог не работает вовсе: нет данных о жизни
 * потока — считаем его живым.
 */
internal const val STREAM_STALE_MS = 15_000L

/**
 * Завершён ли ход модели.
 *
 * `finish` считается завершением при любом непустом значении, включая
 * `finish:"error"`: у провалившегося хода текст ошибки должен быть виден так же,
 * как у успешного, иначе о провале не сообщит ничего. То же для `time.completed`.
 * Последний случай — [STREAM_STALE_MS] от последнего обновления потока: поток,
 * который замолчал, показываем как есть.
 */
internal fun finishedFor(msg: JSONObject): Boolean {
    val time = msg.optJSONObject("time")
    // Порог считаем ТОЛЬКО по streamed. Если сервер его не отдаёт, данных о
    // жизни потока нет, и мы обязаны считать поток живым: иначе на сервере без
    // streamed мысль показывалась бы через 15 секунд — то есть ровно то, что
    // этот фильтр и выпиливает.
    val streamed = time?.optLong("streamed") ?: 0L
    return msg.optString("finish").isNotBlank() ||
        time?.optLong("completed")?.let { it > 0L } == true ||
        (streamed > 0L && System.currentTimeMillis() - streamed > STREAM_STALE_MS)
}

/**
 * Текст сообщения, готовый к показу.
 *
 * Пользовательский текст и служебные сообщения возвращаются как есть: человек
 * вправе написать «что значит `</think>`» в вопросе, и обрезать его до
 * ничего — порча его же реплики, а не чистка.
 *
 * У незавершённого ответа модели (поток ещё идёт) возвращается пустая строка,
 * пока тег не пришёл. Иначе в ленте мигает английский монолог, а озвучка,
 * стартующая по инкременту, успевает произнести первые секунды мысли. Ответ при
 * этом не теряется — он целиком приходит вместе с `finish`, когда тег уже на
 * месте.
 *
 * Побочный эффект, о котором надо знать: у модели БЕЗ think-разметки текст
 * тоже ждёт конца хода, потому что отличить «мысль» от «ответа» по сырому
 * тексту нечем. На практике это почти незаметно — лента обновляется опросом
 * примерно раз в секунду, и короткий ответ приходит целиком вместе с
 * `finish`. Для длинного ответа на английском (а такая модель мысли не пишет
 * вовсе) текст появится в конце, а не по мере набора. Это осознанный размен:
 * чистая лента дороже красивого стрима. Страховка на случай, когда признаков
 * завершения не придёт вовсе, — [STREAM_STALE_MS] внутри [finishedFor].
 *
 * Пустая строка означает «пока нечего показывать» — такую часть в ленту класть
 * нельзя, иначе появится реплика без единого слова.
 */
internal fun answerText(
    msgType: String,
    raw: String,
    finished: Boolean,
): String {
    if (msgType != THINKING_TYPE) return raw
    val cut = raw.indexOf(THINK_CLOSE)
    return if (cut < 0) {
        if (finished) raw else ""
    } else {
        raw.substring(cut + THINK_CLOSE.length).trimStart()
    }
}

/**
 * Кладёт текстовую часть в ленту, если после отрезания мысли что-то осталось.
 * Пустую часть не кладём: в ленте появилась бы реплика без единого слова.
 */
internal fun putText(
    out: JSONArray,
    text: String,
) {
    if (text.isNotBlank()) out.put(JSONObject().put("type", "text").put("text", text))
}
