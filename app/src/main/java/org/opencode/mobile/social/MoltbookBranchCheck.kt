package org.opencode.mobile.social

/**
 * Решение по двум независимым чтениям одной ветки.
 *
 * Вынесено из клиента отдельным объектом, а не парой функций в его companion, по двум
 * причинам, и обе важны.
 *
 * **Ни состояния, ни сети.** [isSettled] и [crossCheck] — чистые функции: на входе два
 * [MoltbookClient.ReplyProbe], на выходе один. Поэтому вся логика «что делать, когда
 * представления разошлись» проверяется тестом без `ServerSocket`, без JSON и без
 * устройства, и покрывается целиком, а не по счастливым случаям.
 *
 * **Отдельное место для решения.** Клиент читает; он же и принимает решение о том, что
 * читать дальше. Смешав эти две роли в одном объекте, мы получили бы счётчик функций,
 * который растёт от каждого добавленного правила. Здесь же правило ровно одно и оно
 * видно целиком: доказательство где-то есть — берём; доказательства нет нигде и хоть одно
 * чтение упало — это «не знаем», а не «ответа нет».
 */
internal object MoltbookBranchCheck {
    /**
     * Исход чтения, который не переиговаривается вторым представлением.
     *
     * Найденный наш ответ или найденная неопубликованная запись решают исход сами, и
     * спорное чтение не имеет права отменить доказанное. А вот `Absent` и `Unknown` —
     * это ровно два вида «не доказано», и они оба требуют второго мнения.
     */
    internal fun isSettled(probe: MoltbookClient.ReplyProbe): Boolean =
        probe !is MoltbookClient.ReplyProbe.Absent && probe !is MoltbookClient.ReplyProbe.Unknown

    /**
     * Решение по двум представлениям одной ветки.
     *
     * Порядок здесь — не «сначала главное», а «сначала то, что доказывает».
     *
     * - Доказательство есть хотя бы в одном представлении — берём его, каким бы ни было
     *   второе: неопубликованная запись на первом чтении уже доказывает, что мы туда
     *   что-то писали, и падение второго чтения этого не отменяет.
     * - Доказательства нет ни в одном, причём хоть одно чтение упало — это `Unknown`, а не
     *   `Absent`. Разница не косметическая: `Absent` разрешает публикацию, а `Unknown`
     *   запрещает её, потому что повторная публикация на недоказанном основании создаёт
     *   второй ответ на вопрос, который уже закрыт.
     * - Оба чтения прошли и оба ничего не нашли — `Absent`, и это единственный случай, где
     *   тик вправе опубликовать своё.
     */
    internal fun crossCheck(
        first: MoltbookClient.ReplyProbe,
        second: MoltbookClient.ReplyProbe,
    ): MoltbookClient.ReplyProbe =
        when {
            isSettled(first) -> first
            isSettled(second) -> second
            second is MoltbookClient.ReplyProbe.Unknown -> second
            else -> first
        }
}
