package org.opencode.mobile.social

import android.content.Context
import android.util.Log
import java.io.File
import java.io.FileOutputStream
import java.io.IOException

/**
 * Журнал проверяющего: отдельное место, куда пишет сверка, а не сам публикатор.
 *
 * Зачем он отдельный от [MoltbookTicker] дайджеста. Дайджест пишет тот же код, который
 * только что отправил POST, и переписывается целиком в каждом тике ([MoltbookTicker.persist]).
 * Если сверка писателя ошиблась, она же спокойно подтвердит саму себя: доказательство и
 * доказывающий — один и тот же код в одном и том же месте, и рядом нет никого, кто мог бы
 * возразить. havenargus сформулировал это как «свидетель, который не умеет отказать —
 * это самоотчёт».
 *
 * Поэтому здесь три правила, и все три проверяемы без сети:
 *
 * 1. **Только добавление.** Файл открывается на дозапись, и никакого пути в коде нет:
 *    `append` умеет единственное действие. Переписать журнал нечем, а значит и незачем —
 *    стёртый факт не восстанавливается задним числом.
 * 2. **Отказ — полноценная запись.** `REFUSED` и `MISMATCH` пишутся так же твёрдо, как
 *    `CONFIRMED`. Молчание об отсутствии доказательства и запись о провале доказательства —
 *    разные факты, и путать их нельзя.
 * 3. **Строка не переносится.** Запись всегда в одну строку: `flush()` и `fd.sync()`
 *    фиксируют ровно нарисованное, а обрыв на середине строки нельзя спутать с новой
 *    записью при чтении.
 *
 * Часовая стрелка не сортирует записи и не заменяет порядок: [at] приходит от того же
 * источника времени, что и остальной журнал, и поэтому две записи одного тика сравнимы.
 */
internal object MoltbookVerifierLog {
    private const val TAG = "MoltbookVerifier"

    /** Имя файла рядом с остальными файлами молтборка. */
    const val FILE_NAME = "verifier.log"

    /**
     * Исходы сверки.
     *
     * `CONFIRMED` пишется тоже: подтверждение, записанное тем же кодом, что и публикация,
     * обязано быть видно рядом с отказом — иначе отказ выглядит как единичный сбой, а не
     * как часть регулярной картины.
     */
    enum class Kind(
        val wire: String,
    ) {
        CONFIRMED("confirmed"),
        MISMATCH("mismatch"),
        REFUSED("refused"),
        DIVERGENCE("divergence"),
    }

    /**
     * Строка журнала — чистая функция, поэтому формат проверяется тестом без файлов.
     *
     * [detail] не доверяем: перевод строки внутри делает запись неоднозначной (одна
     * запись выглядит как две), поэтому любой прогон пробельных символов — переводы
     * строк, табы, неучтённые пробелы — схлопывается в один пробел. Иначе запись
     * нельзя ни прочитать как одну, ни сравнить две, не сходящиеся по остальному.
     */
    internal fun line(
        kind: Kind,
        at: Long,
        postId: String,
        detail: String,
    ): String {
        val safe = detail.replace(Regex("\\s+"), " ")
        return "${at}s ${kind.wire} post=$postId $safe"
    }

    /**
     * Дописать одну запись. Ошибка записи НЕ роняет тик: сверка уже вынесла свой вердикт,
     * а потерянная запись журнала не должна отменять публикацию — она лишь останется
     * незамеченной, и это честнее, чем уронить визит целиком.
     */
    fun append(
        context: Context,
        kind: Kind,
        at: Long,
        postId: String,
        detail: String,
    ) {
        val record = line(kind, at, postId, detail)
        try {
            // Рядом со witness.log, а не рядом с сырыми ответами: это независимая
            // проверка, а не ещё один кусок того, что ушло в сеть. Путь берётся у
            // сторожа, поэтому второй «moltbook» в коде не появляется.
            val target = File(MoltbookWatchdog.logFile(context).parentFile, FILE_NAME)
            FileOutputStream(target, true).use { sink ->
                sink.write(record.toByteArray(Charsets.UTF_8))
                sink.write('\n'.code)
                sink.flush()
                sink.fd.sync()
            }
        } catch (e: IOException) {
            // Только отказ файловой системы: он означает ровно «запись потеряна», и
            // ровно он не должен уносить тик. Всё остальное — ошибка в коде, а не
            // судьба визита, и обязано упасть громко.
            Log.w(TAG, "запись проверки не сохранена: ${e.javaClass.simpleName}: ${e.message}")
        }
    }
}
