package org.opencode.mobile.social

import android.app.AlarmManager
import android.app.PendingIntent
import android.content.Context
import android.content.Intent
import android.os.Environment
import android.os.SystemClock
import android.util.Log
import org.opencode.mobile.server.Workspace
import org.opencode.mobile.social.MoltbookWitness.Entry
import java.io.File

/**
 * Сторож тика: будильник, который проверяет, что тик вообще жив.
 *
 * Задача пришла из чужой критики архитектуры (ricksanchez_c137, 08.10.2026), и
 * формулировка там точна именно потому, что запрещает привычное решение:
 *
 *     «Dead-man's switch: если тикер умер, кто-то должен это заметить —
 *      минимальный дешёвый внешний сторож. Ничто на телефоне не может проверить
 *      себя само: внешний свидетель — monotonic counter + checksum в место,
 *      которое телефон не перепишет.»
 *
 * Отсюда три решения, каждое из которых выглядит нелогичным, пока не объяснишь:
 *
 *  1. Свой будильник, а не проверка внутри тика. Проверка «тик жив» внутри тика
 *     бессмысленна по построению: если будильник тика снят, его код не
 *     запускается, и никакая проверка внутри него не сработает. Сторож поэтому
 *     живёт на ОТДЕЛЬНОЙ записи AlarmManager — она переживает смерть тика,
 *     потому что не зависит от него. Это и есть смысл, а не избыточность.
 *
 *  2. Отвергнуто: ForegroundService. Он жил бы в том же процессе, что и тик,
 *     то есть умер бы ровно вместе с ним (плюс добавил бы уведомление в
 *     шторку, которое пользователь всё равно бы закрыл). Сторож не держит
 *     процесс и не рисует ничего — его единственный выход наружу это запись
 *     в чат, и то не чаще раза в час.
 *
 *  3. Отвергнуто: отдельный процесс (`:process` в манифесте или свой
 *     application-процесс). Тогда watchdog жил бы дольше тика, но погибал бы
 *     вместе с ним при падении всего процесса приложения — то есть при самом
 *     интересном сценарии (OOM после тяжёлого тика). Плюс отдельный процесс
 *     стоит отдельного пула памяти ради файла в несколько килобайт.
 *
 *  4. Отвергнуто: ждать ДВА пропущенных тика перед тревогой («может, агент
 *     просто выбрал длинную паузу»). Причина ждать в том, что паузу выбирает
 *     агент, и она бывает длинной — но отвечать на это удвоением порога
 *     нельзя: тогда тревога приходит не раньше, а позже, и юзер всё это время
 *     уверен, что всё в порядке. Паузу учитывает не ожидание, а порог по
 *     наблюдаемому ритму ([observedLimitMs]): длинная пауза сразу становится
 *     длинным порогом, а не отложенной тревогой.
 *
 * Проверка целостности цепочки живёт в [inspectChain], а не в [inspect]: чтобы
 * сказать «порвано», нужен весь журнал, а не одна запись. [inspect] отвечает
 * только на вопрос «тик молчит» и потому принимает одну голову цепочки.
 */
internal object MoltbookWatchdog {
    private const val TAG = "MoltbookWatchdog"

    /**
     * Журнал тика относительно `filesDir`. Именно он читается наружу через
     * зеркало [MoltbookWitness.MIRROR_RELATIVE].
     *
     * Живёт в стороже, а не в тикере, потому что тик обязан только писать, а
     * читать его журнал — это работа того, кто проверяет. Один путь в одном
     * месте: если бы он был продублирован в тикере и здесь, рано или поздно они
     * разошлись бы, и сторож молчал бы ровно на старом пути.
     */
    const val TICK_STALE_PATH: String = "moltbook/witness.log"

    /**
     * Граница «тик умер» по умолчанию: три часа молчания.
     *
     * Это ФОЛБЭК, а не истина, и разница принципиальна. Паузу между тиками
     * выбирает агент, и законно выбирает до 720 минут
     * ([MoltbookTicker.MAX_NEXT_VISIT_MINUTES]), а юзер в карточке — до 360
     * ([MoltbookScheduler.INTERVAL_CHOICES_MINUTES]). Тик, который честно взял
     * паузу в шесть часов по состоянию ленты, при фиксированном пороге в три
     * часа выглядел бы мёртвым — то есть сторож кричал бы «тик умер» на
     * каждой длинной паузе. А ложная тревога хуже отсутствия тревоги: её
     * перестают читать, и тогда не замечают уже настоящую.
     *
     * Поэтому настоящий порог сторож считает по наблюдаемому ритму — см.
     * [observedLimitMs], — а три часа берёт тогда, когда ритма ещё не из чего
     * взять (первый-второй тик, пустой журнал).
     */
    const val LIMIT_MS_FALLBACK: Long = 3 * 60 * 60 * 1000L

    /**
     * Потолок порога: сутки молчания — это смерть при ЛЮБОМ разрешённом ритме.
     *
     * Нужен потому, что порог считается по истории, а история может быть
     * испорчена: журнал могли перенести с другого телефона, часы могли стоять
     * неделю, между тиками могла пройти пауза в 30 минут, а потом система
     * проснулась через трое суток. Такой промежуток не повод разрешить тику
     * молчать неделю.
     *
     * Число выведено из худшего разрешённого ритма: пауза агента 720 минут плюс
     * её половина на размытие неточного alarm'а — 18 часов, то есть потолок
     * 24 часа оставляет запас и при этом всё равно на треть суток короче
     * «тик жив, он просто очень долго думал».
     */
    const val LIMIT_MS_CEILING: Long = 24 * 60 * 60 * 1000L

    /**
     * Как часто сторож смотрит на журнал.
     *
     * Полчаса против трёхчасового порога: чаще — только расход батареи (48
     * пробуждений в сутки ради записи «всё живо»), реже — тревога приходит на
     * полчаса позже, что на фоне самого инцидента неразличимо. Неточный
     * alarm, а не точный: платформа всё равно соберёт его в батч, а на батарее
     * честнее не требовать попадания в минуту.
     */
    const val CHECK_INTERVAL_MS: Long = 30 * 60 * 1000L

    /**
     * Не чаще одного раза в [STALE_REPEAT_WINDOW_MS].
     *
     * Молчание тика — это надолго, а сторож будится каждые
     * [CHECK_INTERVAL_MS]. Без ограничения журнал заполнился бы воплями о
     * собственном молчании: 500 строк [MoltbookWitness.MAX_LINES] при 48
     * пробуждениях в сутки — это меньше десяти дней истории, а потом ещё и
     * вытеснил бы собой записи настоящего тика, ради наблюдения за которым
     * журнал и ведётся. Подробности подсчёта — в [shouldReportStale].
     */
    const val STALE_REPEAT_WINDOW_MS: Long = 60 * 60 * 1000L

    /** Сторож не видел ни одного свидетельства жизни: «нет журнала» хуже «старый журнал». */
    const val NEVER_SEEN: Long = Long.MAX_VALUE

    /** `seq` отсутствующей записи. Минус — потому что настоящие номера неотрицательны. */
    const val NO_ENTRY_SEQ: Long = -1L

    /** Что сторож понял о тике. */
    sealed interface Verdict {
        /**
         * Тик не оставил следа дольше порога.
         *
         * @property sinceMs сколько миллисекунд прошло с последней записи;
         *   [NEVER_SEEN], если записей не было ни одной.
         * @property lastSeq `seq` последней записи или [NO_ENTRY_SEQ], если
         *   записей не было.
         */
        data class Silent(
            val sinceMs: Long,
            val lastSeq: Long,
        ) : Verdict

        /**
         * Журнал не сходится сам с собой.
         *
         * @property brokenAt `seq` первой плохой записи.
         * @property reason человекочитаемая причина из [MoltbookWitness.verifyChain].
         */
        data class Broken(
            val brokenAt: Long?,
            val reason: String,
        ) : Verdict
    }

    /**
     * Взвести сторож: первая проверка через [CHECK_INTERVAL_MS], далее с тем же
     * периодом.
     *
     * Именно `schedule`, а не [ensureArmed], в местах, где сдвиг — это
     * намерение: после собственной проверки сторож обязан перевзвести себя
     * (см. KDoc [MoltbookWatchdogReceiver]), а при старте serve / после ребута
     * он не должен сдвигать уже живой сторож.
     *
     * @param delayMs через сколько прийти в первый раз.
     */
    fun schedule(
        context: Context,
        delayMs: Long = CHECK_INTERVAL_MS,
    ) {
        val manager = context.getSystemService(Context.ALARM_SERVICE) as? AlarmManager ?: return
        manager.setInexactRepeating(
            AlarmManager.ELAPSED_REALTIME,
            SystemClock.elapsedRealtime() + delayMs,
            CHECK_INTERVAL_MS,
            pendingIntent(context),
        )
        markArmed(context)
        Log.i(TAG, "сторож взведён: проверка раз в ${CHECK_INTERVAL_MS / 60000} мин, порог ${LIMIT_MS_FALLBACK / 3600000} ч")
    }

    /**
     * Снять сторож. Для симметрии с [MoltbookScheduler.cancel] и для честного
     * «выключить автономию» в UI: голый alarm, который продолжает будить
     * процесс после того, как его выключили, — это ровно тот баг, от которого
     * сторож и защищает.
     */
    fun cancel(context: Context) {
        val manager = context.getSystemService(Context.ALARM_SERVICE) as? AlarmManager ?: return
        val intent = pendingIntent(context)
        manager.cancel(intent)
        // Токен уничтожаем вместе с записью: AlarmManager.cancel() убирает
        // только будильник, а токен остаётся зарегистрирован в AMS, и
        // [ensureArmed] потом увидит «живой токен» и решит, что сторож взведён.
        intent.cancel()
        disarm(context)
    }

    /**
     * Забыть метку взведения.
     *
     * Нужно при снятии alarm'а силой системы: метка живёт в SharedPreferences
     * и после перезагрузки остаётся свежей, а [ensureArmed] поверит ей и
     * выйдет рано. Отдельной обработки ребута сторож не имеет намеренно: его
     * поднимает первый же тик через [ensureArmed] (см. KDoc объекта).
     */
    fun disarm(context: Context) {
        prefs(context).edit().remove(KEY_ARMED_AT).apply()
    }

    /**
     * Взвести сторож, только если он не взведён.
     *
     * Вызывается в конце КАЖДОГО тика, и именно «только если не взведён» — не
     * украшение: безусловный перевзвод сдвинул бы следующую проверку на
     * `now + CHECK_INTERVAL_MS` после каждого тика, а тик приходит раз в два
     * часа. Сторож с интервалом в полчаса при тике в два часа проверял бы себя
     * примерно четыре раза за промежуток между тиками и успевал бы пропустить
     * ровно тот тик, ради которого он и нужен. То есть каждый тик молча
     * отодвигал бы тревогу всё дальше — сторож, который следит за тикером, но
     * сам плетётся в хвосте у него же.
     *
     * Проверяются два признака, и оба нужны:
     *
     *  - токен PendingIntent жив (`FLAG_NO_CREATE`) — но он может остаться
     *    живым при снятом alarm'е: `AlarmManager.cancel()` убирает запись, а
     *    токен остаётся;
     *  - метка «когда последний раз точно взвели» не протухла. Метка обновляется
     *    в каждом [schedule], а значит и в каждой собственной проверке сторожа,
     *    поэтому живой сторож её не протухает.
     *
     * @see MoltbookScheduler.ensureScheduled — тот же приём для будильника тика.
     */
    fun ensureArmed(context: Context) {
        val manager = context.getSystemService(Context.ALARM_SERVICE) as? AlarmManager ?: return
        val token =
            PendingIntent.getBroadcast(
                context,
                REQUEST_CODE,
                checkIntent(context),
                PendingIntent.FLAG_NO_CREATE or PendingIntent.FLAG_IMMUTABLE,
            )
        val silence = System.currentTimeMillis() - prefs(context).getLong(KEY_ARMED_AT, 0L)
        // Отрицательная разность = часы перевели назад. Метку считаем протухшей:
        // взвести лишний раз безопасно, а поверить часам после перевода — нет.
        val stale = silence < 0 || silence > stalenessLimitMs()
        if (token != null && !stale) return
        if (token != null) {
            Log.w(TAG, "токен сторожа жив, но с последнего взведения не было ни одной проверки — взвожу заново")
        }
        schedule(context)
    }

    /**
     * Сколько молчания терпим, прежде чем считать сторожа убитым: полторы
     * периода.
     *
     * Первое срабатывание после простоя приходит через целый период, а не
     * сразу, плюс размытие неточного alarm'а. Чистая функция без Context — чтобы
     * формулу нельзя было переписать в двух местах с разными числами, как это
     * уже случилось с порогом в [MoltbookScheduler.stalenessLimitMs].
     */
    fun stalenessLimitMs(periodMs: Long = CHECK_INTERVAL_MS): Long = periodMs + periodMs / 2

    /**
     * Журнал тика — то, что сторож читает.
     *
     * Внутреннее хранилище, а не зеркало: зеркало может отсутствовать (нет
     * «Доступа ко всем файлам»), и сторож, который без него немеет, был бы
     * худшим видом сторожа — зависимым от того, за чем он наблюдает.
     */
    fun logFile(context: Context): File = File(context.filesDir, TICK_STALE_PATH)

    /**
     * Файл зеркала снаружи или `null`, если зеркалить некуда.
     *
     * `null` — штатный ответ, а не ошибка: нет «Доступа ко всем файлам», или
     * внешнее хранилище не смонтировано. Отдельная функция обязана возвращать
     * именно `null`, потому что [MoltbookWitness.mirrorSafely] на `null`
     * молча делает правильную вещь, а вот падение на `SecurityException` внутри
     * тика уводило бы тик в ретрай вместо того, чтобы он отработал.
     *
     * Проверка доступности — ровно та же, что у внешнего workspace
     * ([Workspace.hasAllFilesAccess]), чтобы «есть ли зеркало» и «где вообще
     * работает приложение» не расходились.
     */
    fun mirrorFile(context: Context): File? {
        if (!Workspace.hasAllFilesAccess()) return null
        if (Environment.MEDIA_MOUNTED != Environment.getExternalStorageState()) return null
        return File(Environment.getExternalStorageDirectory(), MoltbookWitness.MIRROR_RELATIVE)
    }

    /**
     * Молчит ли тик. Чистая функция: ни Context, ни файлов, только арифметика.
     *
     * Границы и края, каждый из которых стоит отдельного решения:
     *
     *  - `head == null` — это тоже молчание, причём худшее: нет ни одного
     *    свидетельства жизни за всё время. Отдельной веткой его НЕЛЬЗЯ:
     *    «журнала нет» и «тик умер» требуют от юзера одного и того же действия
     *    (понять, что тик не ходит), и разводить их двумя разными сообщениями
     *    значит заставить человека читать две тревоги об одном инциденте.
     *    [Verdict.Silent.sinceMs] при этом равен [NEVER_SEEN], и это видно
     *    издалека: отпечаток отсутствует, а не «молчит 0 минут».
     *
     *  - Порог строгий `>`, а не `>=`. Ровно на пороге запись ещё не старше
     *    обещанного, а обещанное — это «терпим столько-то молчания». Если бы мы
     *    объявляли смерть на границе, порог означал бы «терпим на миллисекунду
     *    меньше», и каждая пара «будильник сработал с опозданием на миллисекунду,
     *    молчание» давала бы тревогу. Разница во времени тут нулевая (сторож
     *    будится раз в полчаса), но семантика обязана быть ровно одна — иначе
     *    её придётся угадывать заново при каждой правке порога.
     *
     *  - Будущее `at` (откат часов после NTP или ребута) молчанием НЕ является:
     *    разность уходит в минус и `>` не срабатывает. Ложная тревога при
     *    переводе часов обучила бы юзера игнорировать сторожа, а ложное «всё
     *    живо» после перевода назад — это просто отложенная тревога на то
     *    время, на которое часы стояли. Издержка принята осознанно: пока часы
     *    едут назад, порог отсчитывается заново.
     *
     * @param head последняя запись журнала или `null`, если журнала нет.
     * @param now текущее время мс — аргументом, а не из `System`, иначе
     *   функция перестаёт быть проверяемой.
     * @param limitMs сколько молчания терпим.
     * @return вердикт или `null` — тик жив.
     *   [Verdict.Broken] здесь невозможен: для него нужен весь список записей,
     *   см. [inspectChain].
     */
    fun inspect(
        head: Entry?,
        now: Long,
        limitMs: Long = LIMIT_MS_FALLBACK,
    ): Verdict? {
        require(limitMs > 0) { "порог молчания обязан быть положительным, а не $limitMs" }
        if (head == null) return Verdict.Silent(sinceMs = NEVER_SEEN, lastSeq = NO_ENTRY_SEQ)
        val silence = now - head.at
        if (silence > limitMs) return Verdict.Silent(sinceMs = silence, lastSeq = head.seq)
        return null
    }

    /**
     * Полная проверка: сначала целостность цепочки, потом молчание.
     *
     * Цепочка проверяется ПЕРВОЙ, и это не порядок «важное раньше», а порядок
     * доверия: доказанная порча журнала обесценивает любые выводы о времени.
     * Если тик лежит ещё и тихий, сообщение о порче всё равно вернее — молчание
     * могло быть и следствием подмены (тик не пришёл, потому что его убили
     * снаружи).
     *
     * Дописать [MoltbookWitness.KIND_TAMPER] в порванную цепочку её НЕ чинит и
     * не должно: [MoltbookWitness.verifyChain] возвращает первую плохую запись,
     * а не последнюю, поэтому новые записи поверх неё ничего не маскируют. Это
     * ровно тот же запрет, что и в самом журнале — вырезать огрызок, чтобы
     * проверка замолчала, значит научить процесс замазывать собственные следы.
     *
     * @param entries журнал целиком, как его отдаёт [MoltbookWitness.readAll].
     * @return вердикт или `null` — и цепочка цела, и тик не молчит.
     */
    fun inspectChain(
        entries: List<Entry>,
        now: Long,
        limitMs: Long = LIMIT_MS_FALLBACK,
    ): Verdict? {
        val integrity = MoltbookWitness.verifyChain(entries)
        if (integrity.brokenAt != null) return Verdict.Broken(integrity.brokenAt, integrity.reason)
        return inspect(entries.lastOrNull(), now, limitMs)
    }

    /**
     * Наблюдаемый ритм тика из самого журнала — единственный источник, который
     * не врёт и не требует чужих прав.
     *
     * Сторож НЕ читает паузу из настроек тикера: это чужое приватное состояние
     * с чужим ключом, и его пришлось бы либо дублировать здесь (два места с
     * одним числом разъедутся при первой же правке), либо лезть в чужой
     * SharedPreferences (сцепка через строку-ключ, которая ломается молча при
     * переименовании). А в журнале лежит ровно то, что нужно и что нельзя
     * подделать задним числом: моменты, когда тик РЕАЛЬНО стартовал.
     *
     * Промежутки берутся только между [MoltbookWitness.KIND_WAKE], то есть
     * между реальными стартами тика: молчание в эти промежутки не попадает по
     * построению, иначе мёртвый тик сам собой «обосновал» бы длинный порог и
     * сторож замолчал бы навсегда. Берётся САМЫЙ длинный промежуток, а не
     * среднее: одна выбранная агентом длинная пауза должна стать нормой, а
     * усреднение занизило бы порог и вернуло ложные тревоги именно в те дни,
     * когда тик работал правильно.
     *
     * Цена решения честная и её надо знать: если агент законно выбрал паузу в
     * 12 часов, смерть тика обнаружится через 18, а не через 3. Отличить
     * «выбрал длинную паузу» от «умер» по журналу нельзя — и единственная
     * честная плата за это заключается в том, что тревога о приходе паузы
     * вообще не возникает. Обратная цена (фиксированные три часа) — тревога на
     * каждой длинной паузе, то есть ложь вместо тишины.
     *
     * @param entries журнал целиком, тот же, что у [inspectChain].
     * @param fallbackMs порог, когда ритма ещё нет; никогда не опускается ниже него.
     * @return порог молчания: не меньше [fallbackMs] и не больше [LIMIT_MS_CEILING].
     */
    fun observedLimitMs(
        entries: List<Entry>,
        fallbackMs: Long = LIMIT_MS_FALLBACK,
    ): Long {
        val wakeAt = entries.filter { it.kind == MoltbookWitness.KIND_WAKE }.map { it.at }
        // Один старт ритма не задаёт: расстояние «до первого» неизвестно.
        if (wakeAt.size < 2) return fallbackMs
        val gaps = wakeAt.zipWithNext { earlier, later -> later - earlier }
        // Отрицательные промежутки (откат часов) и нули — не ритм, а мусор в данных.
        val positive = gaps.filter { it > 0 }
        // Промежуток длиннее потолка ритмом быть не может: это молчание, во время
        // которого сторож обязан был кричать. Раньше он попадал в выборку, и мёртвый
        // тик, оживший через 29 часов, поднимал себе порог до 43 часов — то есть
        // отключал сторож ровно на тот срок, ради которого тот и написан. Такой
        // промежуток выбрасывается, а не «запоминается как норма».
        val plausible = positive.filter { it <= LIMIT_MS_CEILING }
        val longest = plausible.maxOrNull()
        return when {
            longest != null -> (longest + longest / 2).coerceAtLeast(fallbackMs).coerceAtMost(LIMIT_MS_CEILING)
            // Промежутки были, но все длиннее суток: ритма не видно, история врёт.
            // Молчать месяцем нельзя, поэтому берём максимум разрешённого — но не
            // фолбэк, который трактовал бы непригодную историю как «тик был быстрый».
            positive.isNotEmpty() -> LIMIT_MS_CEILING
            else -> fallbackMs
        }
    }

    /**
     * Не пора ли ещё раз сказать о молчании.
     *
     * Считается по ЗАПИСЯМ журнала, а не по отдельному счётчику в prefs: отдельный
     * счётчик можно сбросить, и тогда журнал перестал бы быть источником
     * правды о собственной частоте. Плюс журнал уже в руках, и лишнего
     * состояния на диске не появляется.
     *
     * Окно — по времени записи ([Entry.at]), а не по времени её добавления:
     * `[STALE_REPEAT_WINDOW_MS]` назад от `now`. Записи прошлых часов сортировать
     * не нужно, условие одностороннее.
     */
    fun shouldReportStale(
        entries: List<Entry>,
        now: Long,
        repeatMs: Long = STALE_REPEAT_WINDOW_MS,
        kinds: Set<String> = setOf(MoltbookWitness.KIND_STALE, MoltbookWitness.KIND_TAMPER),
    ): Boolean = entries.none { it.kind in kinds && it.at >= now - repeatMs }

    /**
     * Текст вердикта для человека — тот, что уходит в чат и в журнал.
     *
     * Формулировки выбраны так, чтобы по одному сообщению было понятно, что
     * делать: в обоих случаях первым идёт ЧТО случилось, вторым — на каком
     * номере записи это видно, чтобы человек мог открыть журнал и проверить
     * сам, а не поверить нам на слово.
     */
    fun describe(verdict: Verdict): String =
        when (verdict) {
            is Verdict.Silent ->
                "Молтбук-сторож: тик молчит ${describeSilence(verdict.sinceMs)} (последний seq ${verdict.lastSeq})"
            is Verdict.Broken ->
                "Молтбук-сторож: журнал порван на seq ${verdict.brokenAt ?: NO_ENTRY_SEQ}: ${detailOf(verdict.reason)}"
        }

    /**
     * Молчание словами: «4 ч 12 мин» или «нет ни одного свидетельства жизни».
     *
     * Чистая функция, потому что формат времени читает человек и проверяется
     * тестом; `LocalDateTime` здесь невозможен не только по вкусу — часовой
     * пояс в сообщении о мёртвом будильнике означал бы две разные длительности
     * для одного инцидента.
     */
    fun describeSilence(silenceMs: Long): String {
        if (silenceMs == NEVER_SEEN) return "нет ни одного свидетельства жизни — тик не писал в журнал ни разу"
        val totalMinutes = silenceMs / 60_000L
        val days = totalMinutes / MINUTES_PER_DAY
        val hours = totalMinutes % MINUTES_PER_DAY / 60
        val minutes = totalMinutes % 60
        return buildString {
            if (days > 0) append("$days д ")
            if (days > 0 || hours > 0) append("$hours ч ")
            append("$minutes мин")
        }
    }

    /**
     * Причина обрыва без служебного префикса `seq=N: `.
     *
     * Причина приходит из журнала уже с номером записи, и в сообщении номер
     * стоит один раз — «порван на seq 42: prevHash не ссылается на
     * предыдущую запись», а не «порван на seq 42: seq=42: …». Если формат
     * причины когда-нибудь изменится, [substringAfter] вернёт строку целиком и
     * сообщение останется читаемым — хуже, чем раньше, но не бессмысленным.
     * Наружу эта подгонка не идёт: в журнал ложится причина как есть.
     */
    fun detailOf(reason: String): String = if (reason.startsWith(SEQ_PREFIX)) reason.substringAfter(REASON_SEPARATOR, reason) else reason

    private fun markArmed(context: Context) {
        prefs(context).edit().putLong(KEY_ARMED_AT, System.currentTimeMillis()).apply()
    }

    private fun prefs(context: Context) = context.getSharedPreferences(PREFS, Context.MODE_PRIVATE)

    private fun checkIntent(context: Context): Intent = Intent(context, MoltbookWatchdogReceiver::class.java).setAction(ACTION_CHECK)

    private fun pendingIntent(context: Context): PendingIntent =
        PendingIntent.getBroadcast(
            context,
            REQUEST_CODE,
            checkIntent(context),
            PendingIntent.FLAG_UPDATE_CURRENT or PendingIntent.FLAG_IMMUTABLE,
        )

    const val ACTION_CHECK: String = "org.opencode.mobile.social.WATCHDOG_CHECK"

    /**
     * Отличается от [MoltbookScheduler.REQUEST_CODE] намеренно: токен
     * PendingIntent опознаётся по компоненту и действию, но лишний
     * различающий код ничего не стоит и делает два будильника различимыми в
     * дампах AlarmManager, где оба выглядят одинаково.
     */
    const val REQUEST_CODE: Int = 4418

    private const val PREFS: String = "moltbook_watchdog"
    private const val KEY_ARMED_AT: String = "armed_at"

    private const val MINUTES_PER_DAY: Long = 24 * 60
    private const val SEQ_PREFIX: String = "seq="
    private const val REASON_SEPARATOR: String = ": "
}
