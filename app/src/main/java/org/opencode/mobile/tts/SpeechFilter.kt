package org.opencode.mobile.tts

/**
 * Что из потока ответов агента вообще можно озвучить, и какая часть снапшота
 * ещё не сказана.
 *
 * Вынесено из [TtsNarrator] потому, что это чистая работа с текстом: ей не
 * нужны ни движок, ни ключи, ни потоки. Побочный плюс — правила можно
 * прогнать в обычном юнит-тесте без телефона.
 */
internal object SpeechFilter {
    /**
     * Доля букв, ниже которой фраза считается неразговорной.
     *
     * Считается как `letters / text.length`, то есть в знаменатель входит ВСЁ:
     * цифры, пробелы, знаки. Каждая цифра добавляет единицу к знаменателю и ноль
     * к числителю, а разделители добавляют ещё. Фразы с числами из-за этого
     * штрафуются дважды и обрываются на пороге: при 0.60 фраза «Промежуточный
     * факт: WAV на полном тексте = 76.3 с, ровно как ожидалось (6733396 байт /
     * 44100 / 16 бит)» давала 0.58 и молчала, хотя это нормальный русский текст.
     *
     * Замер на 309 реальных ответах агента (2071 фрагмент) показал: при 0.60
     * терялось 1% обычной прозы, но 26% фраз с цифрами. Цифры — это как раз то,
     * о чём агент говорит постоянно (rtf, кадры, байты, версии), то есть фильтр
     * резал самое нужное. Порог снижен до 0.5: обычная проза идёт с запасом,
     * цифровые фразы проходят, а строки логов и таблицы по-прежнему отсеиваются.
     *
     * Проверенная альтернатива — доля `alnum` по непробельным символам — на этих
     * же данных хуже: спасала 17 фраз, но начинала терять осмысленные короткие
     * вроде «Запомнила: я Ева».
     */
    private const val MIN_LETTER_RATIO = 0.5

    /** Короче — одиночный символ, вслух нечего читать. */
    private const val MIN_CHUNK_LEN = 2

    /**
     * Меньше четырёх букв — осколки вроде «2.» или «Ищу.», а не фраза. На реальных
     * данных правило срабатывало в основном на номерах списков; полноценных
     * коротких ответов («Да.», «Нет.») в выборке не встретилось, поэтому порог
     * оставлен как есть.
     */
    private const val MIN_LETTERS = 4

    /**
     * Что отдать в очередь. [text] — единственное поле для всех случаев, а
     * [Rewritten.from] и сам класс [Rollback] нужны вызывающему, чтобы понять,
     * сбрасывать ли чанкер.
     */
    sealed interface Delta {
        /** Собственно хвост, который уходит в чанкер. */
        val text: String

        /** Хвост после уже озвученного префикса: обычное дополнение ответа. */
        data class Tail(
            override val text: String,
        ) : Delta

        /** Снапшот перерисован целиком: начало то же, изменилась середина. */
        data class Rewritten(
            override val text: String,
            val from: Int,
        ) : Delta

        /** Текст короче осмотренного: новый ответ или правка, чанкер сбрасывается. */
        data class Rollback(
            override val text: String,
        ) : Delta
    }

    /**
     * Годны ли для озвучки предложение.
     *
     * Через ленту идёт не только ответ ассистента, но и текст мобильного агента —
     * с markdown, таблицами и логами. Такое читать вслух не нужно, поэтому режем
     * по трём признакам: разметка/код, почти нет букв, либо текст состоит в
     * основном из не-буквенных символов (строки логов, таблицы).
     */
    fun isSpeechable(text: String): Boolean {
        val letters = text.count { it.isLetter() }
        val noMarkup = !text.contains("```") && !text.contains('`') && !text.contains('|')
        return text.length >= MIN_CHUNK_LEN &&
            noMarkup &&
            letters >= MIN_LETTERS &&
            letters.toDouble() / text.length >= MIN_LETTER_RATIO
    }

    /**
     * Какая часть снапшота ещё не озвучена.
     *
     * Нужно, потому что снапшот ответа перерисовывается целиком на каждом
     * апдейте поллинга: если брать весь текст заново, уже поставленные в очередь
     * куски терялись бы, а сброс чанкера поднимал бы поколение и гасил озвучку —
     * то есть на каждом апдейте. Раньше здесь стоял безусловный сброс: 46 раз за
     * сессию и 10 сыгранных кусков против 65 синтезированных.
     */
    fun delta(
        text: String,
        consumed: String,
    ): Delta =
        when {
            text.startsWith(consumed) -> Delta.Tail(text.substring(consumed.length))
            text.length >= consumed.length -> {
                val common = commonPrefixLength(text, consumed)
                Delta.Rewritten(text.substring(common), common)
            }
            else -> Delta.Rollback(text)
        }

    /** Длина общего префикса двух строк. */
    private fun commonPrefixLength(
        a: String,
        b: String,
    ): Int {
        val limit = minOf(a.length, b.length)
        var i = 0
        while (i < limit && a[i] == b[i]) i++
        return i
    }
}
